/**
 * ✅ V3.3 安全标题裁剪函数 - 增强版
 * 🎯 专门处理语义完整性，避免残词和未闭合表达，增加语序异常检测
 * @param title 原始标题
 * @param maxLength 最大字符数
 * @returns 裁剪后的标题
 */
export function safeTrimTitle(title: string, maxLength: number): string {
  // 1. 基础清理
  let clean = title
    .replace(/[、,.;，。；、]+$/, '')  // 移除末尾标点
    .replace(/[…\.]+$/, '')           // 移除省略号
    .replace(/(文|工|图|说|表)$/g, '') // 移除常见残词
    .trim();

  // 2. 语序异常检测和修正
  const brokenPatterns = [
    /让我小红书(.*)/,
    /小红书优化(.*)/,
    /工具帮我(.*)/,
    /发现宝藏AI(.*)/,
    /优化关键(.*)/,
    /台、文(.*)/,
    /小红书优化关键(.*)/,
    /工具帮我小红书(.*)/,
    /让我小红书优化(.*)/,
    /小红书优化工具(.*)/,
    /工具帮我优化(.*)/,
    /优化小红书(.*)/,
    /小红书工具(.*)/,
    /工具小红书(.*)/,
    /小红书帮我(.*)/,
    /帮我小红书(.*)/,
    /优化小红书工具(.*)/,
    /小红书工具帮我(.*)/,
    /工具小红书优化(.*)/,
    /优化工具小红书(.*)/
  ];

  // 移除语序异常的结构
  for (const pattern of brokenPatterns) {
    if (pattern.test(clean)) {
      clean = clean.replace(pattern, '').trim();
    }
  }

  // 3. 如果清理后长度符合要求，直接返回
  if (clean.length <= maxLength) {
    return clean;
  }

  // 4. 按字符截断
  let trimmed = clean.slice(0, maxLength);

  // 5. 处理未闭合词 - 更全面的残词列表
  const badEnds = [
    '、', '的', '是', '我', '和', '让', '要', '在', '对', '为', '把', '给', '向',
    '从', '到', '由', '被', '得', '着', '过', '了', '吗', '呢', '啊', '哦', '吧',
    '这', '那', '它', '他', '她', '们', '个', '种', '些', '点', '下', '上', '里',
    '外', '前', '后', '左', '右', '中', '间', '边', '面', '方', '向', '位', '处',
    '时', '分', '秒', '年', '月', '日', '周', '期', '次', '回', '遍', '趟', '趟',
    '件', '条', '张', '片', '块', '本', '册', '页', '章', '节', '段', '句', '词',
    '字', '号', '名', '称', '号', '码', '数', '量', '度', '级', '等', '类', '型',
    '式', '样', '态', '状', '况', '情', '形', '势', '力', '能', '力', '功', '效',
    '果', '用', '处', '途', '路', '道', '法', '术', '技', '艺', '术', '学', '科',
    '研', '究', '探', '索', '寻', '找', '求', '追', '赶', '超', '越', '过', '经',
    '历', '验', '证', '明', '确', '定', '决', '断', '判', '评', '估', '测', '试',
    '验', '证', '实', '现', '表', '达', '表', '示', '说', '讲', '谈', '论', '议',
    '讨', '论', '辩', '争', '吵', '闹', '嚷', '叫', '喊', '呼', '唤', '召', '集',
    '聚', '合', '并', '联', '结', '合', '组', '织', '构', '建', '造', '制', '作',
    '创', '造', '发', '明', '发', '现', '找', '到', '得', '到', '获', '得', '收',
    '获', '取', '拿', '抓', '握', '持', '握', '拿', '抓', '握', '持', '握', '拿'
  ];

  // 6. 循环移除未闭合词，直到找到合适的结尾
  while (badEnds.includes(trimmed[trimmed.length - 1])) {
    trimmed = trimmed.slice(0, -1);
    
    // 防止过度裁剪
    if (trimmed.length < maxLength * 0.7) {
      break;
    }
  }

  // 7. 再次检查语序异常（防止截断后产生新的语序问题）
  for (const pattern of brokenPatterns) {
    if (pattern.test(trimmed)) {
      trimmed = trimmed.replace(pattern, '').trim();
    }
  }

  // 8. 确保结果不为空
  if (trimmed.length === 0) {
    console.warn('⚠️ safeTrimTitle: 裁剪后标题为空，使用默认标题');
    return '智能生成标题';
  }

  return trimmed;
} 